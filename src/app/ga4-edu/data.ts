  /** AEO 삼중 정렬의 기준 문장. 도입부, metaDescription, JSON-LD가 이 문장을 공유한다 */
  definition?: string;
  summary?: string;
  teaches?: string[];
  /** ISO 8601 기간. 예: "PT12M" */
  timeRequired?: string;
  missionCount?: number;
  outcome?: string;
  intro?: string;
  terms?: TermDefinition[];
  steps?: TutorialStep[];
